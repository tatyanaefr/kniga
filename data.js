/* ---------------------------------------------------------------------
   Разбор фразы — общий для приложения и для озвучки.
   Слово: { text — для мамы, emoji, syls — слоги (кружочки),
            audio — озвучка каждого слога, word — озвучка всего слова }
   --------------------------------------------------------------------- */
const STRESS = "́";
function parsePhrase(str) {
  return str.trim().split(/\s+/).map(tok => {
    const bar = tok.lastIndexOf("|");
    const raw = bar >= 0 ? tok.slice(0, bar) : tok;
    const emoji = bar >= 0 ? tok.slice(bar + 1) : "";
    const glue = raw.split("_");
    const w = glue.pop();
    const prefix = glue.join(" ");
    const syls = w.split("-");
    const audio = syls.map((s, i) => cleanSyl((i === 0 && prefix ? prefix + " " : "") + s));
    // настоящее слово (с ударением или «ё») голос говорит слитно; звукоподражание — по слогам через дефис
    const real = syls.length === 1 || w.includes(STRESS) || /ё/i.test(w);
    const word = cleanWord((prefix ? prefix + " " : "") + syls.join(real ? "" : "-"));
    return { text: raw.replace(/_/g, " "), emoji, syls, audio, word };
  });
}
function cleanSyl(s) { return s.toLowerCase().replace(/[^а-яё ]/g, "").trim(); }
function cleanWord(s) { return s.toLowerCase().replace(/[^а-яё́ -]/g, "").trim(); }

/* для озвучки: все кусочки, которые нужно озвучить */
function allAudioTexts() {
  const set = new Set();
  const add = str => parsePhrase(str).forEach(w => { w.audio.forEach(a => a && set.add(a)); if (w.word) set.add(w.word); });
  LEVELS.forEach(l => l.items.forEach(add));
  SOUNDS.forEach(s => { add(s[1]); add(s[2]); });
  add(SAYS);
  CHANTS.forEach(c => add(c[1]));
  Object.values(VOICE).forEach(v => set.add(v));
  return [...set];
}

